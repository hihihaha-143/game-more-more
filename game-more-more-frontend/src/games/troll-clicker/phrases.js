export const trollPhrases = openers.flatMap((opener) =>
  closers.map((closer) => `${opener} ${closer}`),
)

export const PHRASE_COUNT = trollPhrases.length

let phraseBag = []

function refillPhraseBag() {
  phraseBag = trollPhrases.map((_, index) => index)
  for (let i = phraseBag.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[phraseBag[i], phraseBag[j]] = [phraseBag[j], phraseBag[i]]
  }
}

// За один заход не повторяем фразы: мешок тасуется заново только после 2000 штук.
export function getRandomTrollPhrase() {
  if (trollPhrases.length === 0) return '...'
  if (phraseBag.length === 0) refillPhraseBag()
  return trollPhrases[phraseBag.pop()]
}

export function resetPhraseBag() {
  phraseBag = []
}
